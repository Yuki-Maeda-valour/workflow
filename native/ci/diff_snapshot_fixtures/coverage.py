def groups(external,typed):
    result={f'group-{number:02d}':[] for number in RANGES}
    for case_id in list(external)+list(typed):
        line=int(case_id.split('-')[2] if case_id.startswith('legacy-typed-') else case_id.split('-')[1])
        selected=[number for number,intervals in RANGES.items() if any(first<=line<=last for first,last in intervals)]
        if len(selected)!=1:raise AssertionError(f'旧観点の対応が一意でありません: {case_id}')
        result[f'group-{selected[0]:02d}'].append(case_id)
    exact_ids([f'group-{i:02d}' for i in range(1,72)],result)
    if any(not values for values in result.values()):raise AssertionError('旧71観点の到達記録に空欄があります')
    return result
